#!/usr/bin/env python3
"""Corner-radius multipliers from the fits: radius_corner(tau) = rho(tau) * knot_corner(tau)  (linear interpolation between knots).
rho is the base radius (see morph_model.dart).  Writes data/radii_knots.json and prints the Dart constants."""
import json, math, numpy as np, os
here = os.path.dirname(os.path.abspath(__file__))
def ss(x):
    t = min(max(x, 0.0), 1.0); return t * t * (3 - 2 * t)
def rho_open(tau, half):
    return half if tau < 190 else min(half, 30.5 + (82.0 - 30.5) * math.exp(-(tau - 190) / 54.0))
def rho_close(tau, half):
    return min(half, 31.0 + 22.0 * ss(tau / 45.0))
out = {}
for name, rho, edges in (('open', rho_open, list(range(-6, 40, 4)) + list(range(40, 130, 6)) + list(range(130, 400, 20))),
                         ('close', rho_close, list(range(-6, 60, 6)) + list(range(60, 280, 8)) + list(range(280, 400, 40)))):
    js = json.load(open(f'{here}/data/native_fit_{name}.json'))
    knots = {k: [] for k in ('tl', 'tr', 'br', 'bl')}; taus = []
    for a, b in zip(edges, edges[1:] + [edges[-1] + 20]):
        sel = [r for r in js if a <= r['tau'] < b]
        if not sel:
            continue
        taus.append((a + b) / 2)
        for k in knots:
            vals = [min(r[k], 2.5 * min(r['R'] - r['L'], r['B'] - r['T']) / 2) / max(rho(r['tau'], min(r['R'] - r['L'], r['B'] - r['T']) / 2), 1) for r in sel]
            knots[k].append(float(np.median(vals)))
    out[name] = dict(tau=taus, **knots)
    print(name, len(taus))
json.dump(out, open(f'{here}/data/radii_knots.json', 'w'))
def arr(v): return '[' + ', '.join(f'{x:.2f}' for x in v) + ']'
with open(f'{here}/morph_knots.dart', 'w') as f:
    f.write('// generated by gen_knots.py from the corner fits, do not edit by hand\n')
    for name in ('open', 'close'):
        d = out[name]
        f.write(f"const kKnots{name.capitalize()}Tau = {arr(d['tau'])};\n")
        for k in ('tl', 'tr', 'br', 'bl'):
            f.write(f"const kKnots{name.capitalize()}{k.upper()} = {arr(d[k])};\n")
